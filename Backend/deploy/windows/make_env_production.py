"""Create (or update) Backend/.env.production for the hosted setup. Secrets are generated here, never printed.

    .venv\\Scripts\\python.exe deploy\\windows\\make_env_production.py [--domain dashboard.example.com]

Only what differs from .env lives here: .env keeps data paths, email and the other shared settings.
"""
import argparse
import secrets
from pathlib import Path

BACKEND = Path(__file__).resolve().parents[2]
TARGET = BACKEND / ".env.production"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--domain", default="", help="public hostname, e.g. dashboard.technosport.in")
    ap.add_argument("--exports", default=str(Path.home() / "Desktop" / "TD_Data" / "DATA"),
                    help="folder the app exports (Order_Data.csv ...) are dropped into")
    ap.add_argument("--quick-tunnel", action="store_true",
                    help="also accept temporary https://*.trycloudflare.com links (quick_tunnel.ps1, testing only)")
    a = ap.parse_args()

    cur = {}
    if TARGET.exists():
        for line in TARGET.read_text(encoding="utf-8").splitlines():
            if "=" in line and not line.lstrip().startswith("#"):
                k, v = line.split("=", 1)
                cur[k.strip()] = v.strip()

    domain = a.domain.strip().lower() or cur.get("PUBLIC_DOMAIN", "")
    # a real domain replaces the temporary test link; otherwise --quick-tunnel turns it on and re-runs keep it
    quick = a.quick_tunnel or (cur.get("QUICK_TUNNEL") == "1" and not a.domain)
    hosts = ["localhost", "127.0.0.1"] + ([domain] if domain else []) + ([".trycloudflare.com"] if quick else [])
    origins = ([f"https://{domain}"] if domain else []) + (["https://*.trycloudflare.com"] if quick else [])
    values = {
        "DEBUG": "False",
        "DJANGO_SECRET_KEY": cur.get("DJANGO_SECRET_KEY") or secrets.token_urlsafe(50),
        "PUBLIC_DOMAIN": domain,
        "QUICK_TUNNEL": "1" if quick else "0",
        "ALLOWED_HOSTS": ",".join(hosts),
        "CSRF_TRUSTED_ORIGINS": ",".join(origins),
        "CORS_ALLOWED_ORIGINS": ",".join(origins) or "http://localhost:8080",
        "FRONTEND_DIST": str((BACKEND.parent / "Frontend" / "dist").resolve()),
        "CACHE_DIR": str((BACKEND / "data" / "cache").resolve()),
        "TD_EXPORT_DIR": cur.get("TD_EXPORT_DIR") or a.exports,
        "SERVE_HOST": cur.get("SERVE_HOST", "127.0.0.1"),
        "SERVE_PORT": cur.get("SERVE_PORT", "8080"),
    }
    lines = ["# Hosted (production) overrides - read before .env (TD_ENV_FILE). Generated by make_env_production.py.",
             "# Never commit this file."]
    lines += [f"{k}={v}" for k, v in values.items()]
    TARGET.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {TARGET} (domain: {domain or 'not set yet'}; quick test link: {'on' if quick else 'off'})")


if __name__ == "__main__":
    main()
